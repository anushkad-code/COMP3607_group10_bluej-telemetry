package comp3607.group10.telemetry.command;

/**
Somewhere commands can be submitted to be run later. BlueJ listeners depend on this interface,
not on the invoker itself.

@author Anushka Dwarika
*/
public interface CommandQueue {
    /**
    Adds a command to the queue.

    @param command the command to run
    @return true if it was accepted, false after shutdown
    */
    boolean submit(Command command);
}

