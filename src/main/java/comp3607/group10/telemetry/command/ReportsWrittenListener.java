package comp3607.group10.telemetry.command;

import java.nio.file.Path;
import java.util.List;

/**
Told which report files were written, after an export or at shutdown.

@author Anushka Dwarika
*/
public interface ReportsWrittenListener {
    /**
    Called with the files that were written.

    @param files the files that were written
    */
    void reportsWritten(List<Path> files);
}

